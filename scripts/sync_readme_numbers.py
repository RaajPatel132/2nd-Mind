#!/usr/bin/env python3
"""Keep the README's numbers equal to the recorded runs.

    python3 scripts/sync_readme_numbers.py           # rewrite the block
    python3 scripts/sync_readme_numbers.py --check   # exit 1 if the block is out of date

The block between the two markers in README.md is generated from frontend/public/headline.json.
`make headline-check` keeps that file equal to the committed live runs, and the landing page and
/evals read it too, so the README can never say something the site doesn't. A unit test
(backend/tests/unit/test_readme_numbers.py) runs the check, so a stale README fails `make test`.
"""

import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
HEADLINE = ROOT / "frontend" / "public" / "headline.json"
START = "<!-- headline:start (generated by scripts/sync_readme_numbers.py; do not edit) -->"
END = "<!-- headline:end -->"
BLOCK = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)


def run_link(run_id: str, runs: list[dict[str, Any]]) -> str:
    """The run's file in the repository, as a link; the run id alone if the run isn't listed."""
    suite = next((r["suite"] for r in runs if r["id"] == run_id), None)
    if suite is None:
        return f"`{run_id}`"
    return f"[`{run_id}`](backend/evals/runs/{suite}/{run_id}.json)"


def render(headline: dict[str, Any]) -> str:
    """The generated block: a table of the headline numbers, then one line per run behind them."""
    runs: list[dict[str, Any]] = headline["runs"]
    rows = ["| Measure | Result | What it means | Run |", "|---|---|---|---|"]
    for m in headline["metrics"]:
        if m["run"] is None:
            rows.append(f"| {m['label']} | no run yet | | |")
        else:
            rows.append(f"| {m['label']} | **{m['display']}** | {m['detail']} | {run_link(m['run'], runs)} |")
    behind = [
        f"- `{r['suite']}`: {r['passed']} of {r['cases']} cases passed on {r['date']}, "
        f"commit `{r['sha']}`, models {', '.join(f'`{model}`' for model in r['models'])}"
        for r in runs
    ]
    return "\n".join([START, *rows, "", *behind, END])


def sync(readme: str, headline: dict[str, Any]) -> str:
    if len(BLOCK.findall(readme)) != 1:
        raise SystemExit("README.md must contain exactly one headline block (start and end markers)")
    return BLOCK.sub(lambda _m: render(headline), readme)


def main(argv: list[str]) -> int:
    headline = json.loads(HEADLINE.read_text())
    current = README.read_text()
    updated = sync(current, headline)
    if "--check" in argv:
        if updated != current:
            print("README.md's numbers are out of date: run python3 scripts/sync_readme_numbers.py", file=sys.stderr)
            return 1
        print("README.md's numbers are up to date")
        return 0
    README.write_text(updated)
    print("README.md's numbers written" if updated != current else "README.md's numbers already up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
